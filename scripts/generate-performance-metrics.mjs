async function measureBundle(slug, exportName) {
  const entryPath = resolve(root, `.tmp-metrics/${slug}-entry.tsx`);
  const outfile = resolve(root, `.tmp-metrics/${slug}.js`);
  const importPath = resolve(dist, `${slug}.js`);

  if (!existsSync(importPath)) {
    return null;
  }

  await mkdir(dirname(entryPath), { recursive: true });
  await writeFile(
    entryPath,
    `import { ${exportName} } from ${JSON.stringify(importPath)};\nconsole.log(${exportName});\n`,
    "utf8",
  );

  await build({
    entryPoints: [entryPath],
    outfile,
    bundle: true,
    format: "esm",
    platform: "browser",
    packages: "external",
    jsx: "automatic",
    logLevel: "silent",
  });

  const source = await readFile(outfile, "utf8");
  const rawBytes = statSync(outfile).size;
  const gzipBytes = gzipSync(Buffer.from(source)).length;

  return {
    slug,
    rawKb: Number((rawBytes / 1024).toFixed(2)),
    gzipKb: Number((gzipBytes / 1024).toFixed(2)),
    treeShakable: true,
    ssr: slug !== "monaco-editor" && slug !== "flow-chart" && slug !== "data-grid",
  };
}

async function main() {
  if (!existsSync(dist)) {
    console.warn("dist/ not found — run pnpm build first. Skipping performance metrics generation.");
    process.exit(0);
  }

  const metrics = [];
  for (const [slug, exportName] of Object.entries(COMPONENTS)) {
    const result = await measureBundle(slug, exportName);
    if (result) metrics.push(result);
  }

  metrics.sort((a, b) => a.slug.localeCompare(b.slug));

  const contents = `/** Generated by scripts/generate-performance-metrics.mjs — do not edit manually. */
export type ComponentPerformanceMetric = {
  slug: string;
  rawKb: number;
  gzipKb: number;
  treeShakable: boolean;
  ssr: boolean;
};

export const componentPerformanceMetrics: ComponentPerformanceMetric[] = ${JSON.stringify(metrics, null, 2)};

export function getComponentPerformance(slug: string): ComponentPerformanceMetric | undefined {
  return componentPerformanceMetrics.find((metric) => metric.slug === slug);
}
`;

  await writeFile(outFile, contents, "utf8");
  console.log(`Wrote performance metrics for ${metrics.length} components → site/docs/performanceMetrics.ts`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
